def liters_from_dip(tank_id: int, cm: float, mm: float = 0) -> float:
    """
    Переводит показание калибровочной палки в литры.
    cm — целые сантиметры, mm — миллиметры (0-9) сверх них.
    """
    tank = TANKS[tank_id]
    table = tank["table"]
    total_cm = cm + mm / 10.0
    total_cm = max(0, min(total_cm, tank["max_cm"]))

    for i in range(len(table) - 1):
        c0, v0 = table[i]
        c1, v1 = table[i + 1]
        if c0 <= total_cm <= c1:
            t = (total_cm - c0) / (c1 - c0) if c1 != c0 else 0
            m3 = v0 + t * (v1 - v0)
            return round(m3 * 1000)

    return round(table[-1][1] * 1000)


def tank_name(tank_id: int, lang: str = "ru") -> str:
    tank = TANKS[tank_id]
    key = "name_uz" if lang == "uz" else "name_ru"
    return f"{tank[key]} · {tank['fuel']}"
